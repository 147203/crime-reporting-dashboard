<?php

declare(strict_types=1);

namespace App\Support;

use Illuminate\Contracts\Config\Repository;

/**
 * Startup checks on secrets and credentials. Failures name the variable, never its value.
 */
final class Preflight
{
    public const MIN_DB_PASSWORD_LENGTH = 16;

    public const MIN_ADMIN_PASSWORD_LENGTH = 14;

    private const PLACEHOLDER_PREFIX = 'changeme';

    public function __construct(private readonly Repository $config) {}

    /**
     * Checks the running web application needs on every request.
     *
     * @return list<string>
     */
    public function runtimeFailures(): array
    {
        return [...$this->appKeyFailures(), ...$this->appDatabaseFailures(), ...$this->productionFailures()];
    }

    /**
     * The D-25 shortcut (root, blank password) applies only on an explicitly opted-in local machine served on loopback,
     * so a checkout copied to another host falls back to the strict rules.
     */
    public function localDatabaseShortcut(): bool
    {
        $host = (string) parse_url($this->string('app.url'), PHP_URL_HOST);

        return in_array($this->string('app.env'), ['local', 'testing'], true)
            && $this->config->get('database.allow_local_shortcut') === true
            && in_array($host, ['localhost', '127.0.0.1', '::1', '[::1]'], true);
    }

    /**
     * @return list<string>
     */
    private function productionFailures(): array
    {
        if (! $this->isProduction()) {
            return [];
        }

        return array_values(array_filter([
            $this->config->get('app.debug') === true ? 'APP_DEBUG must be false in production.' : null,
            $this->config->get('session.secure') !== true ? 'SESSION_SECURE_COOKIE must be true in production (serve over HTTPS).' : null,
            $this->string('session.driver') !== 'database' ? 'SESSION_DRIVER must be database in production, so sessions can be ended after a password change.' : null,
        ]));
    }

    /**
     * Everything checked by `php artisan app:preflight`.
     *
     * @return list<string>
     */
    public function allFailures(): array
    {
        return [
            ...$this->runtimeFailures(),
            ...$this->testDatabaseFailures(),
            ...$this->adminPasswordFailures(),
        ];
    }

    /**
     * @return list<string>
     */
    public function adminPasswordFailures(): array
    {
        return $this->secretFailures('ADMIN_INITIAL_PASSWORD', $this->string('admin.initial_password'), self::MIN_ADMIN_PASSWORD_LENGTH);
    }

    /**
     * @return list<string>
     */
    private function appKeyFailures(): array
    {
        $key = $this->string('app.key');

        if ($key === '') {
            return ['APP_KEY is not set (run php artisan key:generate).'];
        }

        if (! str_starts_with($key, 'base64:')) {
            return ['APP_KEY must be a base64 key generated by php artisan key:generate.'];
        }

        $decoded = base64_decode(substr($key, 7), true);

        if ($decoded === false || strlen($decoded) !== 32) {
            return ['APP_KEY does not decode to 32 bytes (run php artisan key:generate).'];
        }

        return [];
    }

    /**
     * @return list<string>
     */
    private function appDatabaseFailures(): array
    {
        $failures = [];

        if (! in_array($this->string('database.default'), ['mysql', 'mysql_testing'], true)) {
            $failures[] = 'DB_CONNECTION must be mysql.';
        }

        foreach (['DB_HOST' => 'host', 'DB_DATABASE' => 'database', 'DB_USERNAME' => 'username'] as $variable => $key) {
            if ($this->string("database.connections.mysql.{$key}") === '') {
                $failures[] = "{$variable} is not set.";
            }
        }

        if (! $this->localDatabaseShortcut() && $this->string('database.connections.mysql.username') === 'root') {
            $failures[] = 'DB_USERNAME must be a dedicated application user, not root, outside the local shortcut (D-25).';
        }

        return [
            ...$failures,
            ...$this->databasePasswordFailures('DB_PASSWORD', $this->string('database.connections.mysql.password')),
        ];
    }

    /**
     * Only under the local shortcut is a blank password accepted (XAMPP root, D-25); a placeholder never is.
     *
     * @return list<string>
     */
    private function databasePasswordFailures(string $variable, string $value): array
    {
        if (! $this->localDatabaseShortcut()) {
            return $this->secretFailures($variable, $value, self::MIN_DB_PASSWORD_LENGTH);
        }

        return $this->isPlaceholder($value) ? ["{$variable} still holds the placeholder from .env.example."] : [];
    }

    private function isProduction(): bool
    {
        return $this->string('app.env') === 'production';
    }

    private function isPlaceholder(string $value): bool
    {
        return str_starts_with(strtolower($value), self::PLACEHOLDER_PREFIX);
    }

    /**
     * The test connection is optional (not needed on a demo machine). When present its schema must be a separate *_test schema;
     * in production it must also have its own user and password.
     *
     * @return list<string>
     */
    private function testDatabaseFailures(): array
    {
        $testUser = $this->string('database.connections.mysql_testing.username');

        if ($testUser === '') {
            return [];
        }

        $failures = $this->databasePasswordFailures('DB_TEST_PASSWORD', $this->string('database.connections.mysql_testing.password'));

        if (! $this->localDatabaseShortcut() && hash_equals($this->string('database.connections.mysql.username'), $testUser)) {
            $failures[] = 'DB_TEST_USERNAME must differ from DB_USERNAME.';
        }

        $testDatabase = $this->string('database.connections.mysql_testing.database');

        if (! str_ends_with($testDatabase, '_test')) {
            $failures[] = 'DB_TEST_DATABASE must be set and end in _test.';
        } elseif ($testDatabase === $this->string('database.connections.mysql.database')) {
            $failures[] = 'DB_TEST_DATABASE must differ from DB_DATABASE.';
        }

        $appPassword = $this->string('database.connections.mysql.password');
        if (! $this->localDatabaseShortcut() && $appPassword !== '' && hash_equals($appPassword, $this->string('database.connections.mysql_testing.password'))) {
            $failures[] = 'DB_TEST_PASSWORD must differ from DB_PASSWORD.';
        }

        return $failures;
    }

    /**
     * @return list<string>
     */
    private function secretFailures(string $variable, string $value, int $minLength): array
    {
        if ($value === '') {
            return ["{$variable} is not set."];
        }

        if ($this->isPlaceholder($value)) {
            return ["{$variable} still holds the placeholder from .env.example."];
        }

        if (strlen($value) < $minLength) {
            return ["{$variable} is shorter than {$minLength} characters."];
        }

        return [];
    }

    private function string(string $key): string
    {
        $value = $this->config->get($key);

        return is_scalar($value) ? (string) $value : '';
    }
}
